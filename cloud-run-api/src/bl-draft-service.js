import { strToU8, zipSync } from "fflate";

const FIELDS = [
  ["shipper", "Shipper"],
  ["consignee", "Consignee"],
  ["notifyParty", "Notify Party"],
  ["portOfLoading", "Port of Loading"],
  ["portOfDischarge", "Port of Discharge"],
  ["containerCount", "Container Count"],
  ["grossWeightKg", "Gross Weight (kg)"],
];

const FORMATS = Object.freeze({
  docx: {
    extension: "docx",
    mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
  },
  pdf: { extension: "pdf", mimeType: "application/pdf" },
  txt: { extension: "txt", mimeType: "text/plain; charset=utf-8" },
});

const valueFrom = (field) => {
  const normalized = String(field?.normalizedValue ?? "").trim();
  const raw = String(field?.rawValue ?? "").trim();
  return normalized || raw || "Not available";
};

const fieldValue = (message, id) => {
  const siValue = valueFrom(message.siDocument?.fields?.[id]);
  return siValue !== "Not available" ? siValue : valueFrom(message.draftBlDocument?.fields?.[id]);
};

const cleanFilenamePart = (value) => String(value || "")
  .replace(/[<>:"/\\|?*\u0000-\u001f]/g, " ")
  .replace(/\s+/g, " ")
  .trim()
  .slice(0, 70);

const xmlEscape = (value) => String(value)
  .replaceAll("&", "&amp;")
  .replaceAll("<", "&lt;")
  .replaceAll(">", "&gt;")
  .replaceAll('"', "&quot;")
  .replaceAll("'", "&apos;");

export function buildNormalizedBlContent(message) {
  const sourceLines = [
    "VERICARGO NORMALIZED BILL OF LADING DRAFT",
    "",
    `Source email: ${message.subject || "(No subject)"}`,
    `Shipping Instruction: ${message.siDocument?.filename || "Not available"}`,
    `Draft Bill of Lading: ${message.draftBlDocument?.filename || "Not available"}`,
    "",
    ...FIELDS.map(([id, label]) => `${label}: ${fieldValue(message, id)}`),
    "",
    "Generated by VeriCargo for review. Verify all fields against the source documents before sending.",
  ];
  return sourceLines.join("\n");
}

function createDocx(text) {
  const paragraphs = text.split("\n").map((line) => {
    if (!line) return "<w:p/>";
    return `<w:p><w:r><w:t xml:space="preserve">${xmlEscape(line)}</w:t></w:r></w:p>`;
  }).join("");
  const files = {
    "[Content_Types].xml": strToU8('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>'),
    "_rels/.rels": strToU8('<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>'),
    "word/document.xml": strToU8(`<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${paragraphs}<w:sectPr><w:pgSz w:w="12240" w:h="15840"/><w:pgMar w:top="1080" w:right="1080" w:bottom="1080" w:left="1080"/></w:sectPr></w:body></w:document>`),
  };
  return Buffer.from(zipSync(files, { level: 6 }));
}

const pdfSafe = (value) => String(value)
  .normalize("NFKD")
  .replace(/[^\x20-\x7e]/g, "?")
  .replaceAll("\\", "\\\\")
  .replaceAll("(", "\\(")
  .replaceAll(")", "\\)");

const wrapLine = (line, width = 88) => {
  if (!line) return [""];
  const words = line.split(/\s+/);
  const lines = [];
  let current = "";
  for (const word of words) {
    if (!current) {
      current = word;
    } else if (`${current} ${word}`.length <= width) {
      current += ` ${word}`;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
};

function createPdf(text) {
  const lines = text.split("\n").flatMap((line) => wrapLine(line));
  const pages = [];
  for (let offset = 0; offset < lines.length; offset += 48) pages.push(lines.slice(offset, offset + 48));
  if (!pages.length) pages.push([""]);

  const objects = [];
  const addObject = (content) => {
    objects.push(content);
    return objects.length;
  };
  const catalogId = addObject("");
  const pagesId = addObject("");
  const fontId = addObject("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>");
  const pageIds = [];
  for (const pageLines of pages) {
    const commands = ["BT", "/F1 10 Tf", "12 TL", "54 756 Td"];
    pageLines.forEach((line, index) => {
      if (index) commands.push("T*");
      commands.push(`(${pdfSafe(line)}) Tj`);
    });
    commands.push("ET");
    const stream = commands.join("\n");
    const contentId = addObject(`<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`);
    const pageId = addObject(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${fontId} 0 R >> >> /Contents ${contentId} 0 R >>`);
    pageIds.push(pageId);
  }
  objects[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  objects[pagesId - 1] = `<< /Type /Pages /Count ${pageIds.length} /Kids [${pageIds.map((id) => `${id} 0 R`).join(" ")}] >>`;

  let pdf = "%PDF-1.4\n%\xE2\xE3\xCF\xD3\n";
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(pdf, "binary"));
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefOffset = Buffer.byteLength(pdf, "binary");
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.slice(1).map((offset) => `${String(offset).padStart(10, "0")} 00000 n \n`).join("");
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;
  return Buffer.from(pdf, "binary");
}

export function createBlDocument(message, requestedFormat = "pdf", editedText) {
  const format = String(requestedFormat).toLowerCase();
  const details = FORMATS[format];
  if (!details) {
    const error = new Error("File format must be TXT, PDF, or DOCX.");
    error.statusCode = 400;
    throw error;
  }
  if (editedText !== undefined && typeof editedText !== "string") {
    const error = new Error("Draft BL content must be text.");
    error.statusCode = 400;
    throw error;
  }
  if (editedText?.length > 20000) {
    const error = new Error("Draft BL content must be 20,000 characters or fewer.");
    error.statusCode = 400;
    throw error;
  }
  const text = editedText === undefined ? buildNormalizedBlContent(message) : editedText.replaceAll("\r\n", "\n");
  if (!text.trim()) {
    const error = new Error("Draft BL content cannot be empty.");
    error.statusCode = 400;
    throw error;
  }
  const subjectPart = cleanFilenamePart(message.subject) || message.id || "Draft-BL";
  const filename = `VeriCargo-Draft-BL-${subjectPart}.${details.extension}`;
  const buffer = format === "docx" ? createDocx(text) : format === "pdf" ? createPdf(text) : Buffer.from(text, "utf8");
  return { buffer, filename, format, mimeType: details.mimeType, text };
}
